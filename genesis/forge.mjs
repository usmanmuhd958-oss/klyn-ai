function verifyLayer(cfg) {
  const dir = join(GENESIS, cfg.id);
  const missing = [];
  if (!existsSync(dir)) return { ok: false, reason: 'missing directory genesis/' + cfg.id };
  for (const name of cfg.modules) {
    if (!existsSync(join(dir, name + '.ts'))) missing.push(name + '.ts');
  }
  for (const extra of ['smoke.ts', 'layer.json', 'README.md']) {
    if (!existsSync(join(dir, extra))) missing.push(extra);
  }
  if (!existsSync(join(ROOT, 'genesis-' + cfg.id + '-bootstrap.sh'))) missing.push('genesis-' + cfg.id + '-bootstrap.sh');
  const tsFiles = readdirSync(dir).filter((f) => f.endsWith('.ts') && !f.endsWith('smoke.ts'));
  const moduleCount = tsFiles.length;
  if (moduleCount !== 10) missing.push('module count=' + moduleCount + ' (expected 10 core modules)');
  return missing.length === 0 ? { ok: true, reason: '' } : { ok: false, reason: missing.join(', ') };
}

function verifyAll() {
  let passed = 0;
  let failed = 0;
  for (const cfg of manifest) {
    const result = verifyLayer(cfg);
    if (result.ok) {
      passed += 1;
      console.log('PASS  ' + cfg.id + '  genesis/' + cfg.id + ' — 10/10 modules');
    } else {
      failed += 1;
      console.log('FAIL  ' + cfg.id + '  ' + result.reason);
    }
  }
  console.log('forge verify: ' + passed + '/' + (passed + failed) + ' layers OK');
  return failed === 0;
}

function listLayers() {
  console.log('GENESIS EVOLUTION — V671..V700 (' + manifest.length + ' layers)');
  for (const cfg of manifest) {
    console.log('  ' + cfg.id.padEnd(6) + cfg.codename.padEnd(34) + cfg.name);
  }
}

const command = process.argv[2] ?? 'all';

if (command === 'list') {
  listLayers();
} else if (command === 'verify') {
  process.exitCode = verifyAll() ? 0 : 1;
} else if (command === 'all') {
  for (const cfg of manifest) {
    const summary = materialize(cfg);
    console.log('forge: materialized ' + summary);
  }
  console.log('');
  process.exitCode = verifyAll() ? 0 : 1;
} else {
  const cfg = manifest.find((layer) => layer.id === command);
  if (!cfg) {
    console.error('error: unknown layer "' + command + '" (expected one of: all | verify | list | v671..v700)');
    process.exitCode = 1;
  } else {
    const summary = materialize(cfg);
    console.log('forge: materialized ' + summary);
    const result = verifyLayer(cfg);
    console.log(result.ok ? 'forge: ' + cfg.id + ' verify PASS' : 'forge: ' + cfg.id + ' verify FAIL: ' + result.reason);
    process.exitCode = result.ok ? 0 : 1;
  }
}
