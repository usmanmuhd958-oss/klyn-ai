    '  readonly #log: Logger;',
    '  #bootStartedAt = 0;',
    '',
    '  constructor(layer: string, codename: string, quiet = false) {',
    '    this.layer = layer;',
    '    this.codename = codename;',
    "    this.#log = new Logger(layer + ':' + this.role, quiet ? 3 : 1);",
    '  }',
    '',
    '  start(): void {',
    '    this.#bootStartedAt = Date.now();',
    "    this.#log.info('kernel module started');",
    '  }',
    '',
    '  stop(): void {',
    "    this.#log.info('kernel module stopped');",
    '  }',
    '',
    '  register(module: LayerModule): KernelRecord {',
    '    const existing = this.#records.get(module.name);',
    '    const record: KernelRecord = {',
    '      name: module.name,',
    '      role: module.role,',
    '      status: existing ? existing.status : \'registered\',',
    '      registeredAt: existing ? existing.registeredAt : Date.now(),',
    '    };',
    '    this.#records.set(module.name, record);',
    '    return record;',
    '  }',
    '',
    '  markStarted(name: string): void {',
    '    const record = this.#records.get(name);',
    "    if (record) record.status = 'started';",
    '  }',
    '',
    '  markStopped(name: string): void {',
    '    const record = this.#records.get(name);',
    "    if (record) record.status = 'stopped';",
    '  }',
    '',
    '  get size(): number {',
    '    return this.#records.size;',
    '  }',
    '',
    '  names(): string[] {',
