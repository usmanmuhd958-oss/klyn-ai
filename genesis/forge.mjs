    '    let sum = 0;',
    '    let min = Number.POSITIVE_INFINITY;',
    '    let max = Number.NEGATIVE_INFINITY;',
    '    for (const value of values) {',
    '      sum += value;',
    '      if (value < min) min = value;',
    '      if (value > max) max = value;',
    '    }',
    '    const count = values.length;',
    '    return {',
    '      count,',
    '      sum,',
    '      min,',
    '      max,',
    '      avg: sum / count,',
    '      last: values[count - 1] as number,',
    '    };',
    '  }',
